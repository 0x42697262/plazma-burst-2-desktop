// Plazma Burst 2 dev console. Toggle with Shift+` (~).
//
// - Made for multiplayer: the console works in online matches. Client-only commands
//   change your own game client, not the server.
// - No game functions are patched (the game's anti-tamper check compares function
//   source). Values are forced from an ENTER_FRAME listener on the game stage.
// - Settings, binds, typed commands and profiles are saved to desktop/dev-overrides.json
//   (localStorage when not running inside the desktop wrapper). Editing the file while
//   the game runs reloads it (the wrapper calls pb2dev.reload).
// - The game's globals are obfuscated and change with every game version. They are not
//   written in this code: they come from desktop/dev/names.js, generated by
//   "npm run find-names", and only game/ uses them.
//
// Layout: core/ (helpers), game/ (the game adapter), state/ (settings, binds, history),
// overrides/ (per-frame forcing), triggers/ (map triggers and variables), maps/ (the map
// cache), editor/ (the in-game map editor), ui/ (panel, log, pager), commands/ (one
// module per command group, all in the registry), dispatch.js (running a typed line).
import './commands/index.js';
import { print, TAG } from './ui/log.js';
import { buildPanel, updateStatus, updateStatusIfOpen, openPanel, closePanel, onKeyDownCapture, onKeyUpCapture } from './ui/panel.js';
import { COLOR } from './core/colors.js';
import { errorBudget } from './core/guard.js';
import { plural } from './core/text.js';
import { game } from './game/bindings.js';
import { namesMissing } from './game/names.js';
import { load, reload as reloadStore, settings, binds, profiles, loadProblems, setMapSource } from './state/store.js';
import { currentMapId } from './game/level.js';
import { profileTick } from './commands/profile.js';
import { applyOverrides, onActiveChange } from './overrides/frame.js';
import { syncTriggerHooks } from './triggers/log.js';
import { mapTick } from './maps/cache.js';
import { editorTick } from './editor/index.js';
import { run } from './dispatch.js';

const BOOT_POLL_MS = 200; // how often to look for the game's stage while it loads
const STATUS_EVERY_MS = 500;
const MAP_TICK_MS = 250;
const FRAME_ERRORS_SHOWN = 5;
const MAP_ERRORS_SHOWN = 3;

const reportError = (msg) => print(msg, COLOR.error);

function printProblems() {
  for (const p of loadProblems()) print(`dev-overrides.json: ${p}`, COLOR.warn);
}
const frameGuard = errorBudget(FRAME_ERRORS_SHOWN, reportError);
const mapGuard = errorBudget(MAP_ERRORS_SHOWN, reportError);

function onFrame() {
  frameGuard('Trigger history', syncTriggerHooks);
  frameGuard('Frame', applyOverrides);
  frameGuard('Editor', editorTick);
}

function start(source) {
  buildPanel();
  onActiveChange(updateStatus);
  game.onEnterFrame(onFrame);
  document.addEventListener('keydown', onKeyDownCapture, true);
  document.addEventListener('keyup', onKeyUpCapture, true);
  updateStatus();
  print('Plazma Burst 2 dev console. Type "help". Toggle with Shift+` (~).', COLOR.bright);
  if (namesMissing.length) {
    const msg = `Game names not found: ${namesMissing.join(', ')}. Commands that use them will fail. Run "npm run find-names" (see README.md).`;
    print(msg, COLOR.error);
    console.error(`${TAG} ${msg}`);
  }
  const n = Object.keys(settings.snapshot()).length;
  const p = profiles.names().length;
  print(`Loaded ${plural(n, 'override')}, ${plural(binds.keys().length, 'bind')}${p ? ` and ${plural(p, 'profile')}` : ''} from ${source === 'file' ? 'desktop/dev-overrides.json' : 'localStorage'}.`, COLOR.hint);
  printProblems();
  setInterval(updateStatusIfOpen, STATUS_EVERY_MS);
  setInterval(() => { mapGuard('Map cache', mapTick); mapGuard('Profiles', profileTick); }, MAP_TICK_MS);
}

async function boot() {
  setMapSource(currentMapId);
  const source = await load();
  const timer = setInterval(() => {
    let ready = false;
    try { ready = game.ready(); } catch {}
    if (!ready) return;
    clearInterval(timer);
    start(source);
  }, BOOT_POLL_MS);
}

globalThis.pb2dev = {
  run: (line) => run(line),
  // The wrapper calls this when dev-overrides.json was changed outside the console.
  reload(obj) {
    reloadStore(obj);
    print('dev-overrides.json changed: reloaded', COLOR.hint);
    printProblems();
  },
  // ... or when the file it changed to is not valid JSON: the console keeps what it had.
  fileError(message) {
    print(`dev-overrides.json changed but cannot be read (${message}). Keeping the settings from before, and not saving changes to the file until it is fixed.`, COLOR.error);
  },
  get kv() { return settings.snapshot(); },
  open: () => openPanel(),
  close: () => closePanel(),
};
boot();
