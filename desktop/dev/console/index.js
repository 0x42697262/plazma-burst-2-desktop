// Plazma Burst 2 dev console. Toggle with Shift+` (~).
//
// - Made for multiplayer: the console works in online matches. Client-only commands
//   change your own game client, not the server.
// - No game functions are patched (the game's anti-tamper check compares function
//   source). Values are forced from an ENTER_FRAME listener on the game stage.
// - Settings, binds, typed commands and profiles are saved to desktop/dev-overrides.json
//   (localStorage when not running inside the desktop wrapper). Editing the file while
//   the game runs reloads it (the wrapper calls pb2dev.reload).
// - The game's globals are obfuscated and change with every game version. They are not
//   written in this code: they come from desktop/dev/names.js, generated by
//   "npm run find-names", and only game/ uses them.
//
// Layout: core/ (helpers), game/ (the game adapter), state/ (settings, binds, history),
// overrides/ (per-frame forcing), triggers/ (map triggers and variables), maps/ (the map
// cache), editor/ (the in-game map editor), net/ (the anti-cheat scan's report and the
// network recorder for netlogs/), server/ (the player-hosted dedicated host, "npm run p2p-host"),
// join/ (a private server from the server list), ui/
// (panel, log, pager), commands/ (one module per command group, all in the registry),
// dispatch.js (running a typed line).
import './commands/index.js';
import { print, TAG } from './ui/log.js';
import { buildPanel, updateStatus, updateStatusIfOpen, openPanel, closePanel, onKeyDownCapture, onKeyUpCapture } from './ui/panel.js';
import { COLOR } from '../../../src/console/kernel/core/keys.ts';
import { errorBudget } from '../../../src/console/kernel/core/guard.ts';
import { plural } from '../../../src/console/kernel/core/words.ts';
import { game } from '../../../src/console/kernel/game/bindings.ts';
import { namesMissing, CLIENT_TITLE, FIND_NAMES, SADBURST } from '../../../src/console/kernel/game/names.ts';
import { load, reload as reloadStore, settings, binds, profiles, loadProblems, setMapSource } from '../../../src/console/kernel/state/store.ts';
import { currentMapId } from '../../../src/console/kernel/game/level.ts';
import { applyOverrides, onActiveChange } from './overrides/frame.js';
import { run } from './dispatch.js';
import { SERVER } from '../../../src/console/kernel/core/mode.ts';
import { enabledConsoleFeatures, featureFrameHooks, featureTicks, featureListSections } from '../../../src/console/features.ts';
import { registerListSection } from '../../../src/console/kernel/list-sections.ts';
import { CLIENT_DETAILS } from '../../../src/shared/clients/keys.ts';
import { CLIENT } from '../../../src/shared/features/keys.ts';

// Sad Burst 2 has a settings file of its own (src/shared/clients/keys.ts).
const KV_FILE = CLIENT_DETAILS[SADBURST ? CLIENT.sadburst : CLIENT.official].settingsFileName;
const BOOT_POLL_MS = 200; // how often to look for the game's stage while it loads
const STATUS_EVERY_MS = 500;
const FRAME_ERRORS_SHOWN = 5;

const reportError = (msg) => print(msg, COLOR.error);

function printProblems() {
  for (const p of loadProblems()) print(`${KV_FILE}: ${p}`, COLOR.warn);
}
const frameGuard = errorBudget(FRAME_ERRORS_SHOWN, reportError);

const features = enabledConsoleFeatures();
for (const [name, make] of featureListSections(features)) registerListSection(name, make);
const featureFrame = featureFrameHooks(features);

function onFrame() {
  for (const hook of featureFrame) frameGuard(hook.name, hook.run);
  frameGuard('Frame', applyOverrides);
}

function start(source) {
  buildPanel();
  onActiveChange(updateStatus);
  game.onEnterFrame(onFrame);
  document.addEventListener('keydown', onKeyDownCapture, true);
  document.addEventListener('keyup', onKeyUpCapture, true);
  updateStatus();
  if (!SERVER) print(`${CLIENT_TITLE} dev console. Type "help". Toggle with Shift+\` (~).`, COLOR.bright);
  if (namesMissing.length) {
    const msg = `Game names not found: ${namesMissing.join(', ')}. Commands that use them will fail. Run "${FIND_NAMES}" (see README.md).`;
    print(msg, COLOR.error);
    console.error(`${TAG} ${msg}`);
  }
  const n = Object.keys(settings.snapshot()).length;
  const p = profiles.names().length;
  print(`Loaded ${plural(n, 'override')}, ${plural(binds.keys().length, 'bind')}${p ? ` and ${plural(p, 'profile')}` : ''} from ${source === 'file' ? `desktop/${KV_FILE}` : 'localStorage'}.`, COLOR.hint);
  printProblems();
  setInterval(updateStatusIfOpen, STATUS_EVERY_MS);
  for (const tick of featureTicks(features)) {
    const guard = errorBudget(tick.errorsShown, reportError);
    setInterval(() => guard(tick.name, tick.run), tick.everyMs);
  }
  for (const feature of features) if (feature.start) feature.start();
}

async function boot() {
  setMapSource(currentMapId);
  const source = await load();
  const timer = setInterval(() => {
    let ready = false;
    try { ready = game.ready(); } catch {}
    if (!ready) return;
    clearInterval(timer);
    start(source);
  }, BOOT_POLL_MS);
}

globalThis.pb2dev = {
  run: (line) => run(line),
  // The wrapper calls this when dev-overrides.json was changed outside the console.
  reload(obj) {
    reloadStore(obj);
    print(`${KV_FILE} changed: reloaded`, COLOR.hint);
    printProblems();
  },
  // ... or when the file it changed to is not valid JSON: the console keeps what it had.
  fileError(message) {
    print(`${KV_FILE} changed but cannot be read (${message}). Keeping the settings from before, and not saving changes to the file until it is fixed.`, COLOR.error);
  },
  get kv() { return settings.snapshot(); },
  open: () => openPanel(),
  close: () => closePanel(),
};
boot();
