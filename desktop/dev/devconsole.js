  // ---------------------------------------------------------------------------
  // Pager
  // ---------------------------------------------------------------------------
  // Long lists are built as rows first, then printed one page at a time, so the top of
  // a list never scrolls out of the log (LOG_MAX lines). The last list is kept: "more"
  // prints its next page, "page <n>" any page. A command takes "page <n>" at the end,
  // e.g. "triggers on page 3". Page size: the page_size key (default 200).
  const PAGE_SIZE_DEFAULT = 200;
  let pager = null; // { title, rows, cmd, hint, empty, color, page, pages, size }

  const pageSize = () => (has('page_size') ? kv.page_size : PAGE_SIZE_DEFAULT);

  // Removes a trailing "page <n>" from args. Returns { args, page } (page 1 if absent).
  function takePage(args) {
    const n = args.length;
    if (n >= 2 && ['page', 'pg'].includes(String(args[n - 2]).toLowerCase())) {
      if (!/^\d+$/.test(args[n - 1])) throw new Error('page expects a number, e.g. "page 2"');
      return { args: args.slice(0, n - 2), page: Number(args[n - 1]) };
    }
    return { args, page: 1 };
  }

  // rows: [text, color?] each. cmd: the command that made the list (for the footer).
  // title: first line; hint: last line; empty: printed when there are no rows.
  function showPaged({ title, rows, cmd, hint = '', empty = '', color = '#89D0FF', page = 1 }) {
    const size = pageSize();
    const pages = Math.max(1, Math.ceil(rows.length / size));
    if (!Number.isInteger(page) || page < 1) throw new Error('pages start at 1');
    if (page > pages) throw new Error(`no page ${page}: this list has ${pages} page${pages === 1 ? '' : 's'} of ${size}`);
    pager = { title, rows, cmd, hint, empty, color, page, pages, size };
    printPage();
  }

  function printPage() {
    const { title, rows, cmd, hint, empty, color, page, pages, size } = pager;
    const from = (page - 1) * size;
    const slice = rows.slice(from, from + size);
    print(pages > 1 ? `${title} Page ${page}/${pages}: ${from + 1}-${from + slice.length} of ${rows.length}.` : title, color);
    if (!rows.length && empty) print(empty, '#ffff88');
    for (const [text, c] of slice) print(text, c);
    if (pages > 1) {
      print(page < pages
        ? `Page ${page}/${pages}. "more" = next page, "page <n>" = jump (also "${cmd} page <n>").`
        : `Last page (${pages}/${pages}). "page 1" = back to the top.`, '#ffffff99');
    }
    if (hint) print(hint, '#ffffff99');
  }

  // "more": next page of the last list. "page <n>": page n of it.
  function cmdPage(n) {
    if (!pager) throw new Error('no list to page yet. Try "triggers".');
    const page = n === undefined ? pager.page + 1 : Number(n);
    if (n !== undefined && !/^\d+$/.test(String(n))) throw new Error('usage: page <n>');
    if (n === undefined && page > pager.pages) throw new Error(`already on the last page (${pager.pages}/${pager.pages}). "page 1" goes back to the top.`);
    if (page < 1 || page > pager.pages) throw new Error(`no page ${page}: this list has ${pager.pages} page${pager.pages === 1 ? '' : 's'}`);
    pager.page = page;
    printPage();
  }

  function cmdTriggers(rawArgs) {
    if (!isActive()) throw new Error('start a level first');
    const list = mapList('triggers', 'triggerCount');
    if (!list.length) { print('This map has no triggers', '#ffff88'); return; }
    const verb = (rawArgs[0] || '').toLowerCase();
    if (TRIGGER_RUN_VERBS.includes(verb)) { runTriggerCmd(list, rawArgs.slice(1)); return; }
    const { args, page } = takePage(rawArgs);
    if (verb === 'find' || verb === 'search') { findTriggerActions(list, args.slice(1), page); return; }
    if (verb === 'history' || verb === 'hist' || verb === 'log') { showTriggerHistory(args.slice(1), page); return; }
    const sources = triggerSources();
    const q = args.join(' ').trim();
    const lc = q.toLowerCase();

    // One trigger in detail: "triggers 5", "triggers #5" or "triggers #trigger*5" (uid).
    const byIdx = /^#?\d+$/.test(q) ? Number(q.replace('#', '')) : -1;
    const exact = byIdx >= 0 ? byIdx : list.findIndex((t) => t && String(t.uid).toLowerCase() === lc);
    if (exact >= 0) {
      const t = list[exact];
      if (!t) throw new Error(`no trigger #${exact}. This map has ${list.length} (0-${list.length - 1}).`);
      const by = sources.get(exact);
      const n = t[N.trigActionCount] || 0;
      const rows = [];
      for (let a = 0; a < n; a++) {
        const type = t[N.trigTypes][a];
        const name = ACTION_NAMES[type] ? `  (${ACTION_NAMES[type]})` : '';
        rows.push([`    ${String(a + 1).padStart(3)}. type ${String(type).padEnd(4)} A = ${fmtTarget(t[N.trigTargetA][a])}   B = ${fmtTarget(t[N.trigTargetB][a])}${name}`]);
      }
      print(`Trigger #${exact}${t.uid ? ' ' + t.uid : ''}`, '#89D0FF');
      print(`  ${t[N.trigEnabled] ? 'enabled' : 'disabled'}, calls ${callsText(t)}${t[N.trigAtStart] ? ', runs at map start' : ''}`);
      print(`  started by: ${by ? by.join('; ') : 'nothing found (maybe a shot at an object, or another trigger through a variable)'}`);
      showPaged({ title: `  ${n} action${n === 1 ? '' : 's'} (type = the map editor's action number):`, color: '#ffffff', rows, cmd: `triggers ${exact}`, page });
      return;
    }

    // Summary list, optionally filtered by uid text, "on" or "off".
    const on = list.filter((t) => t && t[N.trigEnabled]).length;
    const rows = [];
    list.forEach((t, i) => {
      if (!t) return;
      const enabled = !!t[N.trigEnabled];
      if (lc === 'on' && !enabled) return;
      if (lc === 'off' && enabled) return;
      if (lc && lc !== 'on' && lc !== 'off' && !String(t.uid).toLowerCase().includes(lc)) return;
      const by = sources.get(i);
      const flags = [t[N.trigAtStart] ? 'at start' : '', by ? `by ${by.length > 1 ? by[0] + ` +${by.length - 1}` : by[0]}` : ''].filter(Boolean).join(', ');
      rows.push([`  #${String(i).padEnd(4)} ${String(t.uid || '-').padEnd(20)} ${enabled ? 'on ' : 'off'}  ${callsText(t).padEnd(12)} ${String(t[N.trigActionCount] || 0).padStart(3)} action${t[N.trigActionCount] === 1 ? ' ' : 's'}  ${flags}`,
        enabled ? undefined : '#ffffff77']);
    });
    const filtered = q ? ` Filter "${q}": ${rows.length} shown.` : '';
    showPaged({
      title: `Triggers: ${list.length} (${on} enabled, ${list.length - on} disabled).${filtered} "triggers <#>" shows one in detail.`,
      rows,
      cmd: q ? `triggers ${q}` : 'triggers',
      empty: lc === 'on' ? '  no enabled triggers' : lc === 'off' ? '  no disabled triggers' : `  no trigger matches "${q}"`,
      page,
    });
  }

  const TRIGGER_RUN_VERBS = ['run', 'activate', 'fire', 'exec'];

  // "triggers run": runs a trigger through the game's own function, the way a shot or
  // a region does: the activator ("the player who started it", used by many actions)
  // is set first. Without "force" the game's rules apply: it must be enabled with calls
  // left, and running uses up a call. With "force" it runs anyway, and its enabled
  // state and calls left are put back afterwards.
  // Multiplayer: the run is sent to the server like a normal one, so other players run
  // it too. Not sent (your client only) when the other clients would refuse it or run
  // it differently: forced on a disabled/used-up trigger, "as" another character (the
  // server always makes the sender the activator), or while spectating.
  function runTriggerCmd(list, args) {
    const usage = 'usage: triggers run <# | uid> [force] [as <char#>]';
    let force = false;
    let activator = game.me();
    const rest = [];
    for (let k = 0; k < args.length; k++) {
      const a = args[k].toLowerCase();
      if (a === 'force' || a === '-f') force = true;
      else if (a === 'as') {
        const t = args[++k];
        if (!/^#?\d+$/.test(t || '')) throw new Error(usage);
        activator = Number(t.replace('#', ''));
        const c = game.chars()[activator];
        if (!c || !c.io || activator >= game.charCount()) throw new Error(`no character #${activator}. Type "chars".`);
      } else rest.push(args[k]);
    }
    if (rest.length !== 1) throw new Error(usage);
    const q = rest[0];
    const idx = /^#?\d+$/.test(q) ? Number(q.replace('#', '')) : list.findIndex((t) => t && String(t.uid).toLowerCase() === q.toLowerCase());
    const t = list[idx];
    if (idx < 0 || !t) throw new Error(`no trigger "${q}". Type "triggers" or "triggers find <text>".`);
    const label = `#${idx}${t.uid ? ' ' + t.uid : ''}`;
    const wasEnabled = t[N.trigEnabled];
    const wasCalls = t[N.trigCalls];
    const usable = wasEnabled && (wasCalls === -1 || wasCalls > 0);
    if (!usable && !force) {
      const why = !wasEnabled ? 'is disabled' : `has no calls left (${callsText(t)})`;
      throw new Error(`trigger ${label} ${why}. "triggers run ${idx} force" runs it anyway.`);
    }
    if (force) {
      t[N.trigEnabled] = true;
      if (wasCalls !== -1 && !(wasCalls > 0)) t[N.trigCalls] = 1;
    }
    const mp = game.isMP();
    const localWhy = !mp ? '' : !usable ? 'it is disabled or used up for the other players'
      : activator !== game.me() ? '"as" another character only works in your game'
        : read('spectating') ? 'you are spectating' : '';
    const send = mp && !localWhy;
    // A synced run uses up a call on every client, so keep the used call here too.
    const restore = force && !send;
    const prevActivator = read('triggerActivator');
    const prevPower = read('triggerPower');
    write('triggerActivator', activator);
    write('triggerPower', 1);
    try {
      call('runTrigger', idx);
    } finally {
      write('triggerActivator', prevActivator);
      write('triggerPower', prevPower);
      if (restore) { t[N.trigEnabled] = wasEnabled; t[N.trigCalls] = wasCalls; }
    }
    if (send) game.sendTriggerRun(idx);
    const n = t[N.trigActionCount] || 0;
    const by = activator === game.me() ? '' : ` as #${activator}`;
    const where = !mp ? '' : send ? ', sent to all players' : '';
    print(`Ran trigger ${label}${by} (${n} action${n === 1 ? '' : 's'})${restore ? ', forced: enabled state and calls left kept' : `, calls ${callsText(t)}`}${where}`, '#66ff88');
    if (mp && !send) print(`Note: ran in your game only, other players do not see it: ${localWhy}.`, WARN_COLOR);
  }

  // "triggers find": triggers whose uid matches, and every action whose A or B matches.
  // Each term is "text" (uid, A or B), "uid:text", "a:text", "b:text" or "type:n"; all
  // terms must match. Text matches anywhere in a value, case-insensitive; a number
  // matches number values exactly (5 does not match 15).
  function findTriggerActions(list, args, page = 1) {
    const usage = 'usage: triggers find <text>  |  uid:<text>  a:<text>  b:<text>  type:<n>  (combine terms, e.g. "type:41 a:sound")';
    if (!args.length) throw new Error(usage);
    const terms = args.map((raw) => {
      const m = raw.match(/^(uid|a|b|type):(.*)$/i);
      const field = m ? m[1].toLowerCase() : 'ab';
      const text = (m ? m[2] : raw).toLowerCase();
      if (!text) throw new Error(usage);
      if (field === 'type' && !/^\d+$/.test(text)) throw new Error('type: expects a number, e.g. type:99');
      return { field, text, num: /^-?\d+(\.\d+)?$/.test(text) ? Number(text) : null };
    });
    const valueMatches = (v, t) => {
      if (v === undefined || v === null) return false;
      if (typeof v === 'number') return t.num !== null && v === t.num;
      const s = String(v).toLowerCase();
      return t.num !== null && /^-?\d+(\.\d+)?$/.test(s) ? Number(s) === t.num : s.includes(t.text);
    };
    const uidMatches = (t, term) => String(t.uid || '').toLowerCase().includes(term.text);

    // "uid:" terms pick which triggers to look at at all; the rest match actions. A bare
    // term may match the uid instead of an action, so "find god_all" lists the #god_all
    // trigger itself as well as the actions pointing at it.
    const uidTerms = terms.filter((term) => term.field === 'uid');
    const rest = terms.filter((term) => term.field !== 'uid');
    const trigRows = [];
    const actRows = [];
    const triggersHit = new Set();
    list.forEach((t, i) => {
      if (!t) return;
      if (!uidTerms.every((term) => uidMatches(t, term))) return;
      // The uid alone answers the whole query: one row for the trigger, not for actions.
      if (rest.every((term) => term.field === 'ab' && uidMatches(t, term))) {
        const n = t[N.trigActionCount] || 0;
        trigRows.push([`  #${String(i).padEnd(4)} ${String(t.uid || '-').padEnd(16)} trigger   ${t[N.trigEnabled] ? 'on ' : 'off'}  ${callsText(t).padEnd(12)} ${String(n).padStart(3)} action${n === 1 ? '' : 's'}`,
          t[N.trigEnabled] ? undefined : '#ffffff77']);
      }
      if (!rest.length) return;  // "uid:" only: the trigger row is the whole answer.
      for (let a = 0; a < (t[N.trigActionCount] || 0); a++) {
        const type = t[N.trigTypes][a], A = t[N.trigTargetA][a], B = t[N.trigTargetB][a];
        const ok = rest.every((term) =>
          term.field === 'type' ? type === term.num
            : term.field === 'a' ? valueMatches(A, term)
              : term.field === 'b' ? valueMatches(B, term)
                : valueMatches(A, term) || valueMatches(B, term));
        if (!ok) continue;
        triggersHit.add(i);
        const name = ACTION_NAMES[type] ? `  (${ACTION_NAMES[type]})` : '';
        actRows.push([`  #${String(i).padEnd(4)} ${String(t.uid || '-').padEnd(16)} action ${String(a + 1).padEnd(3)} type ${String(type).padEnd(4)} A = ${fmtTarget(A)}   B = ${fmtTarget(B)}${name}`,
          t[N.trigEnabled] ? undefined : '#ffffff77']);
      }
    });
    const rows = trigRows.concat(actRows);
    const q = args.join(' ');
    const bits = [];
    if (trigRows.length) bits.push(`${trigRows.length} trigger${trigRows.length === 1 ? '' : 's'} by uid`);
    if (actRows.length) bits.push(`${actRows.length} action${actRows.length === 1 ? '' : 's'} in ${triggersHit.size} trigger${triggersHit.size === 1 ? '' : 's'}`);
    showPaged({
      title: rows.length ? `${bits.join(', ')} match "${q}". "triggers <#>" shows one in full.`
        : `No trigger or action matches "${q}"`,
      color: rows.length ? '#89D0FF' : '#ffff88',
      rows,
      cmd: `triggers find ${q}`,
      page,
    });
  }

  // Action targets are numbers (indexes, values) or text after the map loads.
  const fmtTarget = (v) => (v === undefined || v === null ? '-' : typeof v === 'string' ? JSON.stringify(v.length > 40 ? v.slice(0, 40) + '...' : v) : String(v));

  // ---------------------------------------------------------------------------
  // Map variables
  // ---------------------------------------------------------------------------
  // Triggers keep their state in one object, variable name -> value, emptied whenever a
  // map loads. Values that came from the map are numbers when they look like numbers and
  // strings otherwise, and the "variable equals" actions compare with ===, so a value set
  // here keeps that difference: 5 is the number, "5" is the text.
  const VAR_VERBS = ['set', 'get', 'del', 'unset', 'rm'];

  function mapVars() {
    const v = read('mapVars');
    if (!v) throw new Error('no variables yet: they are created when a map loads');
    return v;
  }

  // 5 -> the number, "5" -> the text, anything else -> the text as typed.
  function parseVarValue(raw) {
    if (raw.length >= 2 && raw.startsWith('"') && raw.endsWith('"')) return raw.slice(1, -1);
    return /^-?\d+(\.\d+)?$/.test(raw) ? Number(raw) : raw;
  }

  // Like fmtTarget, but never shortened: for one value the user asked about.
  const fmtVar = (v) => (v === undefined ? '(not set)' : typeof v === 'string' ? JSON.stringify(v) : String(v));

  function cmdVars(rawArgs) {
    if (!isActive()) throw new Error('start a level first');
    const verb = (rawArgs[0] || '').toLowerCase();
    if (VAR_VERBS.includes(verb)) { writeVar(verb, rawArgs.slice(1)); return; }
    const { args, page } = takePage(rawArgs);
    const vars = mapVars();
    const names = Object.keys(vars).sort();
    const q = args.join(' ').trim();
    const lc = q.toLowerCase();
    const rows = [];
    for (const n of names) {
      if (lc && !n.toLowerCase().includes(lc)) continue;
      rows.push([`  ${n.padEnd(28)} ${fmtTarget(vars[n])}`]);
    }
    showPaged({
      title: `Map variables: ${names.length}.${q ? ` Filter "${q}": ${rows.length} shown.` : ''} "vars set <name> <value>" changes one.`,
      rows,
      cmd: q ? `vars ${q}` : 'vars',
      empty: names.length ? `  no variable name contains "${q}"` : '  no trigger has set a variable yet',
      hint: 'Numbers print bare and text in quotes; "vars get <name>" shows a long value in full. "triggers find <name>" lists the actions that use one.',
      page,
    });
  }

  function writeVar(verb, args) {
    const usage = 'usage: vars set <name> <value>  |  vars get <name>  |  vars del <name>';
    const name = args[0];
    if (!name) throw new Error(usage);
    const vars = mapVars();
    const had = Object.prototype.hasOwnProperty.call(vars, name);
    if (verb === 'get') {
      if (args.length !== 1) throw new Error(usage);
      if (!had) throw new Error(`no variable "${name}". Type "vars" to list them, or "vars ${name}" to search.`);
      print(`${name} = ${fmtVar(vars[name])}`);
      return;
    }
    if (verb !== 'set') {
      if (args.length !== 1) throw new Error(usage);
      if (!had) { print(`${name} is not set`, '#ffff88'); return; }
      const before = vars[name];
      delete vars[name];
      print(`Removed ${name} (was ${fmtVar(before)})`, '#66ff88');
      return;
    }
    if (args.length < 2) throw new Error(usage);
    const before = vars[name];
    const value = parseVarValue(args.slice(1).join(' '));
    vars[name] = value;
    print(`${name} = ${fmtVar(value)}${had ? `  (was ${fmtVar(before)})` : '  (new)'}`, '#66ff88');
    if (!had) print('  No trigger had set it yet, so nothing may read it. "vars" lists the ones in use.', '#ffffff99');
  }

