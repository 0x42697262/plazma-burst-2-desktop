  function applyPlayer(p, running, dt) {
    // God
    for (const o of [...godObjs]) if (o !== p || !kv.god) uninstallGod(o);
    if (kv.god) {
      installGod(p);
      if (p[F.DEAD] && p.hea > 0) p[F.DEAD] = false;
    }

    // Max HP
    if (has('max_hp')) {
      force(p, 'hmax', kv.max_hp);
      if (lastMaxHp.get(p) !== kv.max_hp) { p.hea = kv.max_hp; lastMaxHp.set(p, kv.max_hp); }
    } else if (restore(p, 'hmax')) {
      lastMaxHp.delete(p);
      if (p.hea > p.hmax) p.hea = p.hmax;
    }

    // HP bonus: add only the difference between the wanted bonus and what this character
    // already got, so it is applied once per character object (a new life/level gets it
    // once again) and never adds up frame after frame. Skipped while max_hp forces hmax.
    if (!has('max_hp') && p.hea > 0 && !p[F.DEAD]) {
      const applied = hpBonusApplied.get(p) || 0;
      const want = hpBonusFor(p.hmax - applied); // hmax - applied = the game's own max HP
      if (want !== applied) {
        const newMax = Math.max(1, p.hmax + (want - applied));
        const real = newMax - p.hmax;
        // Record only what was really added (max HP cannot go below 1), so removing the
        // bonus later takes back exactly that much.
        if (real !== 0) {
          p.hmax = newMax;
          // Raising max HP also gives that much HP; lowering it only caps current HP.
          p.hea = Math.max(1, Math.min(p.hea + Math.max(real, 0), p.hmax));
          hpBonusApplied.set(p, applied + real);
        }
      }
    }

    // Speed: add (s - 1) x the game's own walk acceleration for the last tick.
    // (The game's speed field also scales knockback and balance loss, so it is left alone.)
    if (has('speed') && running && p.hea > 0) {
      const s = kv.speed;
      const walk = p[F.WALK];
      if (walk) {
        if (p.stand) p.tox += walk * (2 - p.sit * 0.75) / 2 * 3 * dt * (s - 1);
        else if (s > 1 && p.tox * Math.sign(walk) < 3 * s) p.tox += walk * 0.4 * dt * (s - 1);
      }
    }

    // Jump
    if (has('jump')) force(p, F.JUMP, kv.jump);
    else restore(p, F.JUMP);

    // Gravity off: undo the gravity the last tick added (y moves before gravity is added).
    const fly = kv.fly === true;
    if ((kv.gravity === false || fly) && running && p.hea > 0 && !p.stand) {
      p.toy -= game.getGravity() * dt;
    }
    // Swords: set the game's per-character "swords disabled" flag, then let the game
    // re-evaluate. Maps that disable swords for everyone ("nopsi") still win over "on".
    if (has('swords')) {
      const off = !kv.swords;
      if (p[F.NO_SWORDS] !== off) { force(p, F.NO_SWORDS, off); game.refreshChar(game.me()); }
    } else if (restore(p, F.NO_SWORDS)) {
      game.refreshChar(game.me());
    }

    if (fly && running && p.hea > 0) {
      const fs = has('fly_speed') ? kv.fly_speed : 6;
      if (game.keyUp()) p.toy = -fs;
      else if (game.keyDown()) p.toy = fs;
      else p.toy *= 0.8;
    }
  }

