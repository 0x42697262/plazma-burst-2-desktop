  function gunList() {
    if (gunCatalog) return gunCatalog;
    const models = [];
    const src = String(game.gunFactory());
    // Every model in the factory is compared through strDecode(<string variable>, ...).
    for (const m of src.matchAll(new RegExp(`${escapeRe(N.strDecode)}\\((\\$[^,()]+),`, 'g'))) {
      const v = globalThis[m[1]];
      if (typeof v === 'string' && !models.includes(v)) models.push(v);
    }
    if (!models.length) models.push(...Object.keys(game.gunScripts()));
    gunCatalog = models.map((model) => {
      let name = '';
      try { name = game.gunName(model) || ''; } catch {}
      const kind = model.startsWith('item_') ? 'items' : model.startsWith('gun_') ? 'standard' : 'custom';
      return { model, name: name || model, kind, slot: gunSlot(model) };
    });
    return gunCatalog;
  }

