  function cmdBind(args) {
    if (!args.length) { cmdBinds(); return; }
    const key = parseKeyName(args[0]);
    if (args.length === 1) {
      print(binds[key] ? `${showKey(key)} = ${binds[key]}` : `${showKey(key)} is not bound`, binds[key] ? undefined : '#ffff88');
      return;
    }
    const command = args.slice(1).join(' ');
    const word = args[1].toLowerCase();
    if (!RUN_WORDS.has(word)) throw new Error(`unknown command "${args[1]}". Type "help".`);
    const old = binds[key];
    binds[key] = command;
    saveKv();
    print(`${showKey(key)} = ${command}${old && old !== command ? `  (was: ${old})` : ''}`, '#66ff88');
    const base = key.split('+').pop();
    if (GAME_KEYS[base] !== undefined) {
      print(`  ${showKey(key)} is also a game key (${base === key ? '' : showKey(base) + ': '}${GAME_KEYS[base]}). In levels the bind runs instead.`, WARN_COLOR);
    }
  }

  function cmdUnbind(args) {
    if (args.length !== 1) throw new Error('usage: unbind <key>  |  unbind all');
    if (args[0].toLowerCase() === 'all') {
      const n = Object.keys(binds).length;
      binds = {};
      saveKv();
      print(`Removed ${n} bind${n === 1 ? '' : 's'}`, '#66ff88');
      return;
    }
    const key = parseKeyName(args[0]);
    if (!binds[key]) { print(`${showKey(key)} is not bound`, '#ffff88'); return; }
    print(`Unbound ${showKey(key)} (was: ${binds[key]})`, '#66ff88');
    delete binds[key];
    saveKv();
  }

  function cmdChars() {
    if (!isActive()) throw new Error('start a level first');
    const c = game.chars();
    const me = game.me();
    const p0 = player();
    for (let i = 0; i < game.charCount(); i++) {
      const p = c[i];
      if (!p || !p.io) continue;
      const hp = `${Math.round(p.hea)}/${Math.round(p.hmax)}`;
      const dist = Math.round(Math.hypot(p.x - p0.x, p.y - p0.y));
      const tag = i === me ? ' (you)' : p.team === p0.team ? ' ally' : ' enemy';
      print(`  #${String(i).padEnd(3)} ${String(p.nickname || '-').padEnd(16)} team ${String(p.team).padEnd(3)} hp ${hp.padEnd(11)} ${p.hea > 0 ? 'alive' : 'dead '} ${String(dist).padStart(6)}px${tag}`,
        i === me ? '#66ff88' : undefined);
    }
  }

  function giveGun(gun, upg, targetIdx) {
    const { p, i: ci, who } = targetChar(targetIdx);
    if (!(p.hea > 0) || p[F.DEAD]) throw new Error(`${who === 'you' ? 'you are' : who + ' is'} dead`);
    const me = ci;
    const g = game.spawnGun(gun.model, { x: p.x, y: p.y, upg, command: -1 });
    if (!g) throw new Error(`the game did not create "${gun.model}"`);
    const slot = g[F.G_SLOT];
    const idx = g[F.G_INDEX];
    if (g[F.G_FIXED] || !(slot >= 0 && slot <= 9)) {
      // Grenade items are picked up by walking over them; vehicle guns cannot be carried.
      print(`Spawned ${gun.name} at the feet of ${who}`, '#66ff88');
      return;
    }
    // The game's slot setter drops whatever gun is in that slot, then assigns the new one.
    p['slot' + slot] = idx;
    if (p['slot' + slot] !== idx) {
      print(`Spawned ${gun.name} at the feet of ${who} (slot ${slot} could not be assigned)`, '#ffff88');
      return;
    }
    p.curwea = idx;
    game.refreshChar(me);
    print(`Gave ${who} ${gun.name} [${gun.model}] in slot ${slot}, upgrade ${upg}`, '#66ff88');
  }

  // Same steps as the game's own "move character to region" trigger: shift every
  // physics point of the player and their carried guns, move the camera, play the effect.
  function teleportTo(tx, ty, label) {
    if (!isActive()) throw new Error('start a level first');
    const p = player();
    if (!(p.hea > 0)) throw new Error('you are dead');
    const X = game.ptX(), Y = game.ptY();
    const ref = p[F.REF_PT];
    const u = X[ref] - tx;
    const v = Y[ref] - ty;
    if (!Number.isFinite(u) || !Number.isFinite(v)) throw new Error('could not read your position');
    if (game.cameraFollowsMe()) {
      const cam = globalThis.game;
      cam.x += u;
      cam.y += v;
      cam.clearMCInterpolationData();
      graphics_3d.clearMCInterpolationData();
      graphics_3d_front.clearMCInterpolationData();
    }
    const me = p[F.G_INDEX];
    const owner = game.ptOwner();
    const guns = game.guns();
    const base = game.gunPtBase(), range = game.gunPtRange();
    const interp = game.interpolating();
    const PX = game.ptPrevX(), PY = game.ptPrevY();
    for (let i = 0, n = game.ptCount(); i < n; i++) {
      const o = owner[i];
      const mine = o === me || (o >= base && o < base + range && guns[o - base] && guns[o - base].picken_by === me);
      if (!mine) continue;
      X[i] -= u;
      Y[i] -= v;
      if (interp) { PX[i] -= u; PY[i] -= v; }
      game.clearPtInterp(i);
    }
    try { game.teleportFx(p.x, p.y - 41); } catch {}
    p.x -= u;
    p.y -= v;
    try { game.teleportFx(p.x, p.y - 41); } catch {}
    p[F.AFTER_MOVE]();
    print(`Teleported to ${label ? label + ' at ' : ''}${Math.round(tx)}, ${Math.round(ty)}`, '#66ff88');
  }

  // The game's aim target in world units.
  function teleportToCrosshair() {
    if (!isActive()) throw new Error('start a level first');
    const p = player();
    if (!Number.isFinite(p.tarx) || !Number.isFinite(p.tary)) throw new Error('crosshair position unknown');
    teleportTo(p.tarx, p.tary);
  }

  function cmdTeleport(args) {
    const sub = (args[0] || '').toLowerCase();
    // Old hotkey syntax, now a bind.
    if (sub === 'on') {
      if (args.length !== 2) throw new Error('usage: bind <key> tp   e.g. bind f tp');
      cmdBind([args[1], 'tp']);
      return;
    }
    if (sub === 'off') {
      const keys = Object.keys(binds).filter((k) => binds[k].toLowerCase() === 'tp');
      if (!keys.length) { print('No key is bound to "tp"', '#ffff88'); return; }
      for (const k of keys) cmdUnbind([k]);
      return;
    }
    if (!args.length) { teleportToCrosshair(); return; }
    const num = (s) => /^-?\d+(\.\d+)?$/.test(s);
    if (args.length === 2 && num(args[0]) && num(args[1])) { teleportTo(Number(args[0]), Number(args[1])); return; }
    // Anything else is a character: tp 2 | tp #2 | tp bot | tp to <name>
    if (sub === 'to') args = args.slice(1);
    if (!args.length) throw new Error('usage: tp to <# | name>');
    teleportToChar(args.join(' '));
  }

  // Character by number ("2", "#2") or by part of the nickname.
  function resolveChar(q) {
    const c = game.chars();
    const alive = [];
    for (let i = 0; i < game.charCount(); i++) if (c[i] && c[i].io) alive.push(i);
    if (/^#?\d+$/.test(q)) {
      const i = Number(q.replace('#', ''));
      if (!alive.includes(i)) throw new Error(`no character #${i}. Type "chars".`);
      return i;
    }
    const lq = q.toLowerCase();
    const exact = alive.filter((i) => String(c[i].nickname || '').toLowerCase() === lq);
    const hits = exact.length ? exact : alive.filter((i) => String(c[i].nickname || '').toLowerCase().includes(lq));
    if (hits.length === 1) return hits[0];
    if (!hits.length) throw new Error(`no character named "${q}". Type "chars".`);
    throw new Error(`"${q}" matches ${hits.length} characters: ${hits.map((i) => `#${i} ${c[i].nickname}`).join(', ')}. Use the #.`);
  }

  function teleportToChar(q) {
    if (!isActive()) throw new Error('start a level first');
    const i = resolveChar(q);
    if (i === game.me()) throw new Error('that is you');
    const t = game.chars()[i];
    const X = game.ptX(), Y = game.ptY(), ref = t[F.REF_PT];
    const x = X[ref], y = Y[ref];
    if (!Number.isFinite(x) || !Number.isFinite(y)) throw new Error(`could not read the position of #${i}`);
    teleportTo(x, y, `#${i} ${t.nickname || ''}`.trim());
  }

  function cmdPos() {
    if (!isActive()) throw new Error('start a level first');
    const p = player();
    const X = game.ptX(), Y = game.ptY(), ref = p[F.REF_PT];
    print(`you: ${Math.round(X[ref])}, ${Math.round(Y[ref])}   crosshair: ${Math.round(p.tarx)}, ${Math.round(p.tary)}`);
  }

  // Same steps as the game's own drop (V key), without its conditions (it refuses e.g.
  // while in a vehicle or when the gun cannot be thrown): empty the slot, toss the gun
  // along the aim angle, wake its physics points, re-equip.
  function dropGun(p, slot) {
    const idx = p['slot' + slot];
    if (!(idx >= 0)) return null;
    const g = game.guns()[idx];
    // The slot setter clears picken_by and, for you, blocks re-pickup for 1 second.
    p['slot' + slot] = -1;
    if (p['slot' + slot] !== -1) throw new Error(`slot ${slot} could not be emptied`);
    if (p.curwea === idx) p.curwea = -1;
    if (g) {
      const a = g[N.gunPtA], b = g[N.gunPtB];
      const VX = read('ptVelX'), VY = read('ptVelY'), X = game.ptX();
      const ang = p[N.aimAngle] || 0, dir = p[N.facing] || 0;
      VX[a] += Math.sin(ang) * 7; VY[a] += Math.cos(ang) * 7 - 2;
      VX[b] += Math.sin(ang) * 1; VY[b] += Math.cos(ang) * 1 + 2;
      X[a] += dir * 20; X[b] += dir * 20;
      call('wakePt', a);
      call('wakePt', b);
    }
    return g;
  }

  function cmdDrop(args) {
    const usage = 'usage: drop  |  drop <slot 1-9>  |  drop all  (add "from <char#>" for a bot)';
    let target;
    const fromAt = args.findIndex((a) => a.toLowerCase() === 'from');
    if (fromAt !== -1) {
      const t = args[fromAt + 1];
      if (!/^#?\d+$/.test(t || '') || args.length !== fromAt + 2) throw new Error(usage);
      target = Number(t.replace('#', ''));
      args = args.slice(0, fromAt);
    }
    if (args.length > 1) throw new Error(usage);
    const { p, i, who } = targetChar(target);
    const a = (args[0] || '').toLowerCase();
    let slots;
    if (a === 'all') slots = [1, 2, 3, 4, 5, 6, 7, 8, 9];
    else if (/^[1-9]$/.test(a)) slots = [Number(a)];
    else if (!a) {
      const s = [1, 2, 3, 4, 5, 6, 7, 8, 9].find((n) => p.curwea >= 0 && p['slot' + n] === p.curwea);
      if (s === undefined) throw new Error(`${who === 'you' ? 'you are' : who + ' is'} not holding a carried gun (swords or vehicle gun)`);
      slots = [s];
    } else throw new Error(usage);
    const dropped = [];
    for (const s of slots) {
      const g = dropGun(p, s);
      if (g) dropped.push(`${game.gunName(g.model) || g.model || 'gun'} (slot ${s})`);
    }
    if (!dropped.length) {
      print(a === 'all' ? `${who === 'you' ? 'You have' : who + ' has'} no guns` : `Slot ${slots[0]} is empty`, '#ffff88');
      return;
    }
    game.refreshChar(i);
    print(`${who === 'you' ? 'Dropped' : who + ' dropped'}: ${dropped.join(', ')}`, '#66ff88');
  }

  function cmdGive(args) {
    const usage = 'usage: give <# | model | name> [upgrade 0-3] [to <char#>]. Type "guns" / "chars".';
    if (!args.length) throw new Error(usage);
    let target;
    const toAt = args.findIndex((a) => a.toLowerCase() === 'to');
    if (toAt !== -1) {
      const t = args[toAt + 1];
      if (!/^#?\d+$/.test(t || '') || args.length !== toAt + 2) throw new Error(usage);
      target = Number(t.replace('#', ''));
      args = args.slice(0, toAt);
    }
    let upg = 3;
    if (args.length > 1 && /^\d+$/.test(args[args.length - 1])) {
      const n = Number(args.pop());
      if (n > 3) throw new Error(`upgrade must be 0-3. The slot is fixed per gun (see "guns"), e.g. the defibrillator is always slot 6.`);
      upg = n;
    }
    if (!args.length) throw new Error(usage);
    giveGun(resolveGun(args.join(' ')), upg, target);
  }

