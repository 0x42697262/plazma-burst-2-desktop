  const isDown = (c) => !!c && (c[F.DEAD] === true || c[F.DYING] === true || !(c.hea > 0));

  // Revives character i to full HP the same way a defibrillator does: stands the body
  // up where it lies, clears the dead/dying flags, re-equips. Returns true on success.
  // Body parts: [part HP field, "broken" flag, share of HP the game gives the part at spawn].
  // The game never revives a character whose head is destroyed (BODY[0] or BODY[1] broken),
  // so those are repaired first. Values from the character constructor (frame2.js ~7768).
  const BODY = [
    [N.headHp, N.headOff, 0.4],         // head blown off (headshot, gib)
    [N.faceHp, N.faceGone, 0.6],        // head destroyed
    [N.legsHp, N.legsBroken, 0.5],      // lower body broken
    [N.armsHp, N.armsBroken, 0.4],      // arms broken
  ];

  // Gives every body part its spawn HP back and lets the game restore the visuals.
  function repairBody(i, c) {
    let broken = 0;
    const hp = Math.max(Number(c.hmax) || 100, 1);
    for (const [part, flag, share] of BODY) {
      if (c[flag] === true) broken++;
      if (!(c[part] > 0) || c[flag] === true) c[part] = Math.max(hp * share, 30);
    }
    if (broken) game.updateBody(i);
    return broken;
  }

  function reviveChar(i) {
    const c = game.chars()[i];
    if (!c || !c.io || i >= game.charCount()) throw new Error(`no character #${i}. Type "chars".`);
    if (!isDown(c)) return false;
    const repaired = repairBody(i, c);
    if (repaired) print(`  repaired ${repaired} broken body part${repaired === 1 ? '' : 's'}`, '#ffffff99');
    // The game sets HP to 10 x power when reviving, so power = max HP / 10 gives full HP.
    game.healChar(i, c, Math.max(1, (Number(c.hmax) || 100) / 10));
    if (isDown(c)) {
      const still = BODY.filter(([, flag]) => c[flag] === true).length;
      throw new Error(`the game refused to revive #${i}${still ? ` (${still} body part${still === 1 ? '' : 's'} still broken)` : ''}`);
    }
    return true;
  }

