// A private server: the site's cookies cleared and none set, so the page never has your login.
async function startLoggedOut() {
  const { removed } = await applyLogin(session.defaultSession.cookies, {}, HOST);
  if (removed.length) log.info(`Cleared saved site cookies: ${removed.join(', ')} (your PB2 account is not used on a private server)`);
}

// The private server being played on is trusted with exactly its saved certificate, and
// with nothing else. Every other site, and that address when no private server is
// chosen, is checked as usual.
function pinServerCertificates() {
  const { X509Certificate } = require('crypto');
  let warned = null;
  session.defaultSession.setCertificateVerifyProc((request, callback) => {
    const target = joinTarget;
    if (!target || request.hostname !== target.host) { callback(-3); return; }
    let fingerprint = '';
    try { fingerprint = new X509Certificate(request.certificate.data).fingerprint256; } catch {}
    if (fingerprint === target.fingerprint) { callback(0); return; }
    if (warned !== target.id) {
      warned = target.id;
      log.error(`Private server: the certificate at ${target.hostPort} is not the saved one (got ${fingerprint || 'none'}); not connecting`);
    }
    callback(-2);
  });
}

// Login: each time the official server is chosen, the site's cookies are cleared, then
// the credentials, if any, are set (env vars PB2_LOGIN, PB2_PASSWORD, PB2_UID win over
// desktop/credentials.json). Without them the game starts logged out. See desktop/login.js.
async function applyCredentials() {
  const credentials = loadCredentials(path.join(__dirname, 'credentials.json'));
  const { removed, set } = await applyLogin(session.defaultSession.cookies, credentials, HOST);
  if (removed.length) log.info(`Cleared saved site cookies: ${removed.join(', ')}`);
  if (set.length) log.info(`Logged in from credentials: ${set.join(', ')}`);
  else log.info('No credentials (desktop/credentials.json or PB2_LOGIN/PB2_PASSWORD/PB2_UID): starting logged out.');
}

async function listLocalMaps() {
  try {
    const files = await fs.readdir(MAPS_DIR);
    return files
      .filter((f) => MAP_EXTS.includes(path.extname(f).toLowerCase()) && !f.startsWith('.'))
      .map((f) => LOCAL_MAP_PREFIX + path.basename(f, path.extname(f)));
  } catch {
    return [];
  }
}

async function findLocalMap(name) {
  let files;
  try {
    files = await fs.readdir(MAPS_DIR);
  } catch {
    return null;
  }
  const want = name.toLowerCase();
  for (const ext of MAP_EXTS) {
    const hit = files.find((f) => f.toLowerCase() === want + ext);
    if (hit) return path.join(MAPS_DIR, hit);
  }
  return null;
}

// Answers the game's map download (POST /pb2/server.php, rq=cmap) for local-* IDs.
// Returns null for anything else so the request goes to the real server.
// Other IDs: served from desktop/maps when fast_maps is on, otherwise downloaded and
// saved there.
async function serveLocalMap(request, ctx) {
  const body = new URLSearchParams(await request.clone().text());
  if (body.get('rq') !== 'cmap') return null;
  const id = (body.get('cmap') || '').trim();
  if (!id.toLowerCase().startsWith(LOCAL_MAP_PREFIX)) return serveServerMap(request, id, ctx);
  const file = await findLocalMap(id.slice(LOCAL_MAP_PREFIX.length));
  if (!file) {
    log.error(`Local map not found: ${id} (looked in ${MAPS_DIR})`);
    return new Response(`${SHARED.map.notPublished} />`, { headers: { 'Content-Type': 'text/plain' } });
  }
  log.info(`Serving local map ${id} from ${file}`);
  const text = (await fs.readFile(file, 'utf8')).replace(/^\uFEFF/, '').trim();
  return new Response(text, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
}

async function serveServerMap(request, id, ctx) {
  if (!id) return null;
  if (fastMapsOn()) {
    const saved = await readSavedMap(id);
    if (saved) {
      log.info(`Fast load: map ${id} from ${path.join(MAPS_DIR, mapFileName(id))}`);
      return new Response(saved, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
    }
  }
  const res = await ctx.fetch(request);
  if (!res.ok) return res;
  const text = await res.text();
  saveMap(id, text).catch((e) => {
    if (!text.startsWith(SHARED.map.notPublished)) log.error(`Could not save map ${id}: ${e.message}`);
  });
  return new Response(text, { status: res.status, headers: { 'Content-Type': res.headers.get('content-type') || 'text/plain; charset=utf-8' } });
}

// A file of the console, or null when the path leaves desktop/dev/console.
async function serveConsoleFile(rel) {
  const file = path.resolve(DEV_CONSOLE_DIR, rel);
  if (path.relative(DEV_CONSOLE_DIR, file).startsWith('..') || !types[path.extname(file)]) return null;
  try {
    const data = await fs.readFile(file);
    return new Response(data, { headers: { 'Content-Type': types[path.extname(file)], 'Cache-Control': 'no-store' } });
  } catch {
    return new Response('Not found', { status: 404 });
  }
}

// The dev console's files, and its local key-value store (desktop/dev-overrides.json).
// The window as it looks now, as screenshots/pb2-<date>_<time>.png. Returns the path
// from the repository root.
async function saveScreenshot(win) {
  if (!win) throw new Error('no game window');
  const png = (await win.webContents.capturePage()).toPNG();
  await fs.mkdir(SCREENSHOT_DIR, { recursive: true });
  const d = new Date();
  const two = (n) => String(n).padStart(2, '0');
  const stamp = `${d.getFullYear()}-${two(d.getMonth() + 1)}-${two(d.getDate())}_${two(d.getHours())}-${two(d.getMinutes())}-${two(d.getSeconds())}`;
  // Several in one second: pb2-<stamp>-2.png and so on.
  for (let n = 1; ; n++) {
    const file = path.join(SCREENSHOT_DIR, `pb2-${stamp}${n > 1 ? `-${n}` : ''}.png`);
    try {
      await fs.writeFile(file, png, { flag: 'wx' });
      return path.relative(path.join(__dirname, '..'), file);
    } catch (e) {
      if (e.code !== 'EEXIST') throw e;
    }
  }
}

async function serveDev(request, url, ctx) {
  const name = decodeURIComponent(url.pathname.slice(DEV_PREFIX.length));
  if (name.startsWith(ROUTE.console)) {
    const res = await serveConsoleFile(name.slice(ROUTE.console.length));
    if (res) return res;
  }
  if (name === ROUTE.names) {
    let data;
    try {
      data = await fs.readFile(DEV_NAMES);
    } catch {
      data = 'globalThis.PB2_NAMES = null; console.error("names.js missing: run npm run find-names");';
    }
    return new Response(data, { headers: { 'Content-Type': types['.js'], 'Cache-Control': 'no-store' } });
  }
  if (name === ROUTE.opcodes) {
    let data;
    try {
      data = await fs.readFile(DEV_OPCODES);
    } catch {
      data = 'globalThis.PB2_OPCODES = null;';
    }
    return new Response(data, { headers: { 'Content-Type': types['.js'], 'Cache-Control': 'no-store' } });
  }
  if (name === ROUTE.maps) {
    return new Response(JSON.stringify(await listLocalMaps()), {
      headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' },
    });
  }
  // Multiplayer map cache, used by the dev console (maps arrive over the game socket).
  if (name === ROUTE.saveMap && request.method === 'POST') {
    try {
      return new Response(await saveMap(url.searchParams.get('id'), await request.text()));
    } catch (e) {
      return new Response(e.message, { status: 400 });
    }
  }
  if (name === ROUTE.saveEdited && request.method === 'POST') {
    try {
      const saved = await saveEditedMap(url.searchParams.get('name'), await request.text(), url.searchParams.get('overwrite') === '1');
      return new Response(JSON.stringify(saved), { headers: { 'Content-Type': 'application/json' } });
    } catch (e) {
      return new Response(e.message, { status: e.status || 500 });
    }
  }
  if (name === ROUTE.mapFile) {
    const text = await readSavedMap(url.searchParams.get('id'));
    return text
      ? new Response(text, { headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' } })
      : new Response('Not found', { status: 404 });
  }
  if (name === ROUTE.screenshot && request.method === 'POST') {
    if (ctx.remote) {
      if (Date.now() - (ctx.lastShot || 0) < REMOTE_SCREENSHOT_MS) return new Response('one screenshot every 2 s', { status: 429 });
      ctx.lastShot = Date.now();
    }
    try {
      return new Response(JSON.stringify({ file: await saveScreenshot(ctx.window) }), { headers: { 'Content-Type': 'application/json' } });
    } catch (e) {
      return new Response(e.message, { status: 500 });
    }
  }
  const net = await serveNetLog(name, request, url, ctx);
  if (net) return net;
  if (name === ROUTE.kv) {
    if (request.method === 'PUT') {
      let obj;
      try {
        obj = JSON.parse(await request.text());
      } catch {
        return new Response('Invalid JSON', { status: 400 });
      }
      if (!obj || typeof obj !== 'object' || Array.isArray(obj)) {
        return new Response('Expected a JSON object', { status: 400 });
      }
      if (!(await ctx.kvFile.write(obj))) {
        return new Response('dev-overrides.json was edited; the console reloads it instead', { status: 409 });
      }
      return new Response('ok');
    }
    return new Response(await ctx.kvFile.read(), { headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' } });
  }
  return new Response('Not found', { status: 404 });
}

// A new hook plan for this page load; prints what loaded and what did not.
function buildHookPlan() {
  const names = hooks.loadNames(DEV_NAMES);
  try {
    hookPlan = hooks.build({ gameDir: ROOT, hooksDir: HOOKS_DIR, names });
  } catch (e) {
    log.error(`Hooks: not loaded: ${e.message}`);
    hookPlan = null;
    return;
  }
  hookPlan.names = names;
  for (const [level, text] of hooks.describe(hookPlan)) log[level](text);
}

// hooks/... requests: the runtime, one hook file, or send() messages for this terminal.
async function serveHooks(request, url) {
  const name = decodeURIComponent(url.pathname.slice(HOOKS_PREFIX.length));
  const js = (text) => new Response(text, { headers: { 'Content-Type': types['.js'], 'Cache-Control': 'no-store' } });
  if (!hookPlan) return new Response('No hooks loaded', { status: 404 });
  if (name === hooks.ROUTES.runtime) return js(hooks.runtimeScript(hookPlan, hookPlan.names));
  if (name.startsWith(hooks.ROUTES.hook) && name.endsWith('.js')) {
    const text = hooks.hookScript(hookPlan, name.slice(hooks.ROUTES.hook.length, -'.js'.length));
    return text ? js(text) : new Response('Not found', { status: 404 });
  }
  if (name === hooks.ROUTES.send && request.method === 'POST') {
    let batch = [];
    try { batch = JSON.parse(await request.text()); } catch {}
    for (const { hook, msg } of Array.isArray(batch) ? batch : []) {
      log.info(`[hook ${hook}] ${typeof msg === 'string' ? msg : JSON.stringify(msg)}`);
    }
    return new Response('ok');
  }
  return new Response('Not found', { status: 404 });
}

async function serveLocal(url, ctx) {
  let rel = decodeURIComponent(url.pathname.slice(PREFIX.length));
  if (rel === '' || rel.endsWith('/')) rel += 'index.html';
  if ((DEV_ENABLED || HOOKS_ENABLED || ctx.remote || ctx.server || joinTarget) && rel === 'index.html') {
    const html = await fs.readFile(path.join(ROOT, 'index.html'), 'utf8');
    let out = html;
    if (HOOKS_ENABLED) {
      buildHookPlan();
      // Before the game's first script, so handlers exist before any game code runs.
      if (hookPlan) out = hooks.injectTags(out, hookPlan);
      if (hookPlan && hookPlan.hooks.length && out === html) {
        // Without the runtime, patched scripts would call a PB2Hooks that does not exist:
        // serve the original scripts instead.
        log.error('Hooks: could not inject into index.html (no <script> tag); no hooks this load');
        hookPlan = null;
      }
    }
    if (DEV_ENABLED) {
      // After the game's own scripts; fall back to the end of <body> if the tag changed.
      const before = out;
      out = out.includes(MAIN_SCRIPT_TAG)
        ? out.replace(MAIN_SCRIPT_TAG, MAIN_SCRIPT_TAG + DEV_SCRIPT_TAG)
        : out.replace(/<\/body>/i, DEV_SCRIPT_TAG + '</body>');
      if (out === before) log.error('Dev console: could not inject into index.html');
    }
    if (joinTarget && !ctx.remote && !ctx.server) {
      const at = out.search(/<script\b/i);
      if (at < 0) {
        log.error('Private server: could not prepare index.html (no <script> tag); not serving it');
        return new Response('Not available', { status: 503 });
      }
      out = out.slice(0, at) + joinPageScript(joinTarget) + out.slice(at);
    }
    if (ctx.server) {
      // The dedicated host: PB2_SERVER before every other script, and chat lines (the
      // game traces each one when asked) to the terminal.
      const at = out.search(/<script\b/i);
      if (at < 0 || !out.includes(FLASH_SCRIPT_TAG)) {
        log.error('Dedicated host: could not prepare index.html (no <script> tag or no scripts/flash.js); not serving it');
        return new Response('Not available', { status: 503 });
      }
      out = out.slice(0, at) + serverPageScript(serverPage) + out.slice(at);
      out = out.replace(FLASH_SCRIPT_TAG, FLASH_SCRIPT_TAG + SERVER_TRACE_SCRIPT_TAG);
    } else if (log.on('debug')) {
      if (out.includes(FLASH_SCRIPT_TAG)) out = out.replace(FLASH_SCRIPT_TAG, FLASH_SCRIPT_TAG + TRACE_SCRIPT_TAG);
      else log.warn('Verbose: scripts/flash.js not found in index.html; the game\'s trace() stays silent');
    }
    if (ctx.remote) {
      // A tester's game: PB2_REMOTE before every other script (desktop/remote/lockdown.js).
      // Without it the console would show "js" and the host's paths: no page at all then.
      const at = out.search(/<script\b/i);
      if (at < 0) {
        log.error('Remote play: could not mark index.html as remote (no <script> tag); not serving it');
        return new Response('Not available', { status: 503 });
      }
      out = out.slice(0, at) + REMOTE_PAGE_SCRIPT + out.slice(at);
    }
    return new Response(out, { headers: { 'Content-Type': types['.html'] } });
  }
  // A game script some hook changed: served from the plan (the file on disk is untouched).
  if (hookPlan && hookPlan.files.has(rel)) {
    return new Response(hookPlan.files.get(rel), { headers: { 'Content-Type': types['.js'], 'Cache-Control': 'no-store' } });
  }
  const file = path.join(ROOT, path.normalize(rel));
  if (!file.startsWith(ROOT + path.sep)) {
    return new Response('Forbidden', { status: 403 });
  }
  try {
    const data = await fs.readFile(file);
    return new Response(data, {
      status: 200,
      headers: { 'Content-Type': types[path.extname(file)] || 'application/octet-stream' },
    });
  } catch {
    return new Response('Not found', { status: 404 });
  }
}

