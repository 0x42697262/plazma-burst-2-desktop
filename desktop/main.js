// Plazma Burst 2 desktop wrapper.
// Serves the local game copy under its real URL so the game behaves exactly
// like the official site (main server, login cookies, multiplayer).
// Every other request is passed through to the real network.
const { app, BrowserWindow, dialog, protocol, net, session } = require('electron');
const fs = require('fs/promises');
const fsSync = require('fs');
const path = require('path');
const vm = require('vm');
const { loadCredentials, applyLogin } = require('./login');

// Game files, downloaded with "npm run fetch-game". Override with PB2_GAME_DIR.
const ROOT = path.resolve(process.env.PB2_GAME_DIR || path.join(__dirname, '..', 'game'));
const HOST = 'www.plazmaburst2.com';
const VERSION = readGameVersion();
const PREFIX = `/h5/versions/${VERSION}/`;
const START_URL = `https://${HOST}${PREFIX}`;

// Dev console (Shift+` key). Disable with PB2_DEV=0.
const DEV_ENABLED = process.env.PB2_DEV !== '0';
// Routes and map markers shared with the console (desktop/dev/console/shared.json).
const SHARED = require('./dev/console/shared.json');
const ROUTE = SHARED.routes;
const DEV_PREFIX = PREFIX + SHARED.devDir;
// The console: ES modules under desktop/dev/console/, served as __dev/console/*.
const DEV_CONSOLE_DIR = path.join(__dirname, 'dev', 'console');
const DEV_CONSOLE_ENTRY = 'index.js';
// Obfuscated game names for this game version, generated by "npm run find-names".
const DEV_NAMES = path.join(__dirname, 'dev', 'names.js');
const DEV_KV_FILE = path.join(__dirname, 'dev-overrides.json');
const MAIN_SCRIPT_TAG = '<script src="scripts/main.js"></script><script>//# sourceURL=scripts/main.js</script>';
const DEV_SCRIPT_TAG = `<script src="${SHARED.devDir}${ROUTE.names}"></script>`
  + `<script type="module" src="${SHARED.devDir}${ROUTE.console}${DEV_CONSOLE_ENTRY}"></script>`;

// The version folder the files came from (written by tools/fetch-game.js). The game is
// served under that same URL so it behaves like the official site.
function readGameVersion() {
  if (process.env.PB2_VERSION) return process.env.PB2_VERSION;
  try {
    return JSON.parse(fsSync.readFileSync(path.join(ROOT, 'pb2-version.json'), 'utf8')).version;
  } catch {
    return null;
  }
}

// Warns when names.js was generated for a different game version.
function checkNamesFile() {
  let text;
  try {
    text = fsSync.readFileSync(DEV_NAMES, 'utf8');
  } catch {
    console.error('Dev console: desktop/dev/names.js is missing. Run "npm run find-names".');
    return;
  }
  const m = text.match(/^\s*version:\s*"([^"]*)"/m);
  if (m && m[1] !== VERSION) {
    console.error(`Dev console: names.js is for game ${m[1]} but the game is ${VERSION}. Run "npm run find-names".`);
  }
  if (/NOT FOUND/.test(text)) console.error('Dev console: names.js has names that were not found; some commands will fail.');
}

// Local maps: type "local-<name>" as the Map ID in Campaign > Custom Map.
// Loads desktop/maps/<name>.xml (or .txt / no extension). Plain map XML or the
// server's compressed "<q." format both work. Re-read on every load.
const MAPS_DIR = path.join(__dirname, 'maps');
const LOCAL_MAP_PREFIX = 'local-';
const MAP_EXTS = ['.xml', '.txt', ''];

// Map cache: every map the game downloads (single-player custom maps over HTTP,
// multiplayer maps from the page through __dev/savemap) is saved to
// desktop/maps/<map id>.xml as plain, uncompressed XML, one tag per line. Dev console
// keys (in dev-overrides.json): save_maps (default on) and fast_maps (default off:
// on = load maps from desktop/maps instead of downloading them again).
function readDevKv() {
  try {
    return JSON.parse(fsSync.readFileSync(DEV_KV_FILE, 'utf8')) || {};
  } catch {
    return {};
  }
}
const saveMapsOn = () => readDevKv().save_maps !== false;
const fastMapsOn = () => readDevKv().fast_maps === true;

// Map ID -> file name. IDs look like "author-name" (spaces allowed); anything that is
// not safe in a file name becomes %XX.
const mapFileName = (id) => id.replace(/[^A-Za-z0-9 _.\-]/g, (c) => '%' + c.charCodeAt(0).toString(16).padStart(2, '0')) + '.xml';

// The server sends maps in a compressed "<q." text format. It is unpacked with the
// game's own function from scripts/libs/xml.js, run in a sandbox.
let unpackMap = null;
function decompressMap(text) {
  if (!text.startsWith(SHARED.map.compressedPrefix)) return text;
  if (!unpackMap) {
    const ctx = {};
    ctx.globalThis = ctx;
    vm.createContext(ctx);
    vm.runInContext(fsSync.readFileSync(path.join(ROOT, '_strings.js'), 'utf8'), ctx);
    const src = fsSync.readFileSync(path.join(ROOT, 'scripts', 'libs', 'xml.js'), 'utf8');
    vm.runInContext(src, ctx);
    const m = src.match(/function (\$[^\s(]+)\(str\)\s*\{\s*for\(i=/);
    if (!m) throw new Error('map decompressor not found in scripts/libs/xml.js');
    unpackMap = vm.runInContext(m[1], ctx);
  }
  const out = unpackMap(text);
  if (out.startsWith(SHARED.map.compressedPrefix)) throw new Error('map is still compressed after unpacking');
  return out;
}

// The server sends a map as one long line of self-closing tags. It is saved one tag
// per line so the files are readable and diff cleanly: the game's parser skips whatever
// sits between tags. Quoted attribute values are left alone, brackets inside them too.
function beautifyMap(text) {
  const lines = [];
  let line = '';
  let quoted = false;
  for (const c of text) {
    if (quoted) {
      line += c;
      if (c === '"') quoted = false;
      continue;
    }
    if (c === '<' && line.trim()) {
      lines.push(line.trim());
      line = '';
    }
    line += c;
    if (c === '"') quoted = true;
  }
  if (line.trim()) lines.push(line.trim());
  return lines.length ? lines.join('\n') + '\n' : '';
}

// Returns one of SHARED.saveResult: saved, same or off. Throws on bad input.
async function saveMap(id, raw) {
  if (!saveMapsOn()) return SHARED.saveResult.off;
  id = String(id || '').trim();
  if (!id || id.toLowerCase().startsWith(LOCAL_MAP_PREFIX)) throw new Error('no map ID');
  const text = decompressMap(String(raw || '').replace(/^\uFEFF/, '').trim());
  if (!text.startsWith('<') || text.startsWith(SHARED.map.notPublished)) throw new Error('not map XML');
  const file = path.join(MAPS_DIR, mapFileName(id));
  const out = beautifyMap(text);
  try {
    if ((await fs.readFile(file, 'utf8')) === out) return SHARED.saveResult.same;
  } catch {}
  await fs.mkdir(MAPS_DIR, { recursive: true });
  await fs.writeFile(file, out);
  console.log(`Saved map ${id} to ${file} (${text.length} chars)`);
  return SHARED.saveResult.saved;
}

// Saved map for a server map ID, or null.
async function readSavedMap(id) {
  try {
    return await fs.readFile(path.join(MAPS_DIR, mapFileName(String(id || '').trim())), 'utf8');
  } catch {
    return null;
  }
}

const types = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.json': 'application/json',
  '.css': 'text/css', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.ttf': 'font/ttf', '.otf': 'font/otf',
};

// Login: every start clears the site's cookies, then sets the credentials, if any
// (env vars PB2_LOGIN, PB2_PASSWORD, PB2_UID win over desktop/credentials.json).
// Without them the game starts logged out. See desktop/login.js.
async function applyCredentials() {
  const credentials = loadCredentials(path.join(__dirname, 'credentials.json'));
  const { removed, set } = await applyLogin(session.defaultSession.cookies, credentials, HOST);
  if (removed.length) console.log(`Cleared saved site cookies: ${removed.join(', ')}`);
  if (set.length) console.log(`Logged in from credentials: ${set.join(', ')}`);
  else console.log('No credentials (desktop/credentials.json or PB2_LOGIN/PB2_PASSWORD/PB2_UID): starting logged out.');
}

async function listLocalMaps() {
  try {
    const files = await fs.readdir(MAPS_DIR);
    return files
      .filter((f) => MAP_EXTS.includes(path.extname(f).toLowerCase()) && !f.startsWith('.'))
      .map((f) => LOCAL_MAP_PREFIX + path.basename(f, path.extname(f)));
  } catch {
    return [];
  }
}

async function findLocalMap(name) {
  let files;
  try {
    files = await fs.readdir(MAPS_DIR);
  } catch {
    return null;
  }
  const want = name.toLowerCase();
  for (const ext of MAP_EXTS) {
    const hit = files.find((f) => f.toLowerCase() === want + ext);
    if (hit) return path.join(MAPS_DIR, hit);
  }
  return null;
}

// Answers the game's map download (POST /pb2/server.php, rq=cmap) for local-* IDs.
// Returns null for anything else so the request goes to the real server.
// Other IDs: served from desktop/maps when fast_maps is on, otherwise downloaded and
// saved there.
async function serveLocalMap(request) {
  const body = new URLSearchParams(await request.clone().text());
  if (body.get('rq') !== 'cmap') return null;
  const id = (body.get('cmap') || '').trim();
  if (!id.toLowerCase().startsWith(LOCAL_MAP_PREFIX)) return serveServerMap(request, id);
  const file = await findLocalMap(id.slice(LOCAL_MAP_PREFIX.length));
  if (!file) {
    console.error(`Local map not found: ${id} (looked in ${MAPS_DIR})`);
    return new Response(`${SHARED.map.notPublished} />`, { headers: { 'Content-Type': 'text/plain' } });
  }
  console.log(`Serving local map ${id} from ${file}`);
  const text = (await fs.readFile(file, 'utf8')).replace(/^\uFEFF/, '').trim();
  return new Response(text, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
}

async function serveServerMap(request, id) {
  if (!id) return null;
  if (fastMapsOn()) {
    const saved = await readSavedMap(id);
    if (saved) {
      console.log(`Fast load: map ${id} from ${path.join(MAPS_DIR, mapFileName(id))}`);
      return new Response(saved, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
    }
  }
  const res = await net.fetch(request, { bypassCustomProtocolHandlers: true });
  if (!res.ok) return res;
  const text = await res.text();
  saveMap(id, text).catch((e) => {
    if (!text.startsWith(SHARED.map.notPublished)) console.error(`Could not save map ${id}: ${e.message}`);
  });
  return new Response(text, { status: res.status, headers: { 'Content-Type': res.headers.get('content-type') || 'text/plain; charset=utf-8' } });
}

// A file of the console, or null when the path leaves desktop/dev/console.
async function serveConsoleFile(rel) {
  const file = path.resolve(DEV_CONSOLE_DIR, rel);
  if (path.relative(DEV_CONSOLE_DIR, file).startsWith('..') || !types[path.extname(file)]) return null;
  try {
    const data = await fs.readFile(file);
    return new Response(data, { headers: { 'Content-Type': types[path.extname(file)], 'Cache-Control': 'no-store' } });
  } catch {
    return new Response('Not found', { status: 404 });
  }
}

// The dev console's files, and its local key-value store (desktop/dev-overrides.json).
async function serveDev(request, url) {
  const name = decodeURIComponent(url.pathname.slice(DEV_PREFIX.length));
  if (name.startsWith(ROUTE.console)) {
    const res = await serveConsoleFile(name.slice(ROUTE.console.length));
    if (res) return res;
  }
  if (name === ROUTE.names) {
    let data;
    try {
      data = await fs.readFile(DEV_NAMES);
    } catch {
      data = 'globalThis.PB2_NAMES = null; console.error("names.js missing: run npm run find-names");';
    }
    return new Response(data, { headers: { 'Content-Type': types['.js'], 'Cache-Control': 'no-store' } });
  }
  if (name === ROUTE.maps) {
    return new Response(JSON.stringify(await listLocalMaps()), {
      headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' },
    });
  }
  // Multiplayer map cache, used by the dev console (maps arrive over the game socket).
  if (name === ROUTE.saveMap && request.method === 'POST') {
    try {
      return new Response(await saveMap(url.searchParams.get('id'), await request.text()));
    } catch (e) {
      return new Response(e.message, { status: 400 });
    }
  }
  if (name === ROUTE.mapFile) {
    const text = await readSavedMap(url.searchParams.get('id'));
    return text
      ? new Response(text, { headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' } })
      : new Response('Not found', { status: 404 });
  }
  if (name === ROUTE.kv) {
    if (request.method === 'PUT') {
      let obj;
      try {
        obj = JSON.parse(await request.text());
      } catch {
        return new Response('Invalid JSON', { status: 400 });
      }
      if (!obj || typeof obj !== 'object' || Array.isArray(obj)) {
        return new Response('Expected a JSON object', { status: 400 });
      }
      await fs.writeFile(DEV_KV_FILE, JSON.stringify(obj, null, 2) + '\n');
      return new Response('ok');
    }
    let text = '{}';
    try {
      text = await fs.readFile(DEV_KV_FILE, 'utf8');
    } catch {}
    return new Response(text, { headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' } });
  }
  return new Response('Not found', { status: 404 });
}

async function serveLocal(url) {
  let rel = decodeURIComponent(url.pathname.slice(PREFIX.length));
  if (rel === '' || rel.endsWith('/')) rel += 'index.html';
  if (DEV_ENABLED && rel === 'index.html') {
    const html = await fs.readFile(path.join(ROOT, 'index.html'), 'utf8');
    // After the game's own scripts; fall back to the end of <body> if the tag changed.
    const out = html.includes(MAIN_SCRIPT_TAG)
      ? html.replace(MAIN_SCRIPT_TAG, MAIN_SCRIPT_TAG + DEV_SCRIPT_TAG)
      : html.replace(/<\/body>/i, DEV_SCRIPT_TAG + '</body>');
    if (out === html) console.error('Dev console: could not inject into index.html');
    return new Response(out, { headers: { 'Content-Type': types['.html'] } });
  }
  const file = path.join(ROOT, path.normalize(rel));
  if (!file.startsWith(ROOT + path.sep)) {
    return new Response('Forbidden', { status: 403 });
  }
  try {
    const data = await fs.readFile(file);
    return new Response(data, {
      status: 200,
      headers: { 'Content-Type': types[path.extname(file)] || 'application/octet-stream' },
    });
  } catch {
    return new Response('Not found', { status: 404 });
  }
}

app.whenReady().then(async () => {
  if (!VERSION || !fsSync.existsSync(path.join(ROOT, 'index.html'))) {
    const msg = `No game files found in ${ROOT}.\n\nRun "npm run fetch-game" first (see README.md).`;
    console.error(msg);
    dialog.showErrorBox('Plazma Burst 2: game files missing', msg);
    app.quit();
    return;
  }
  console.log(`Game ${VERSION} from ${ROOT}`);
  if (DEV_ENABLED) checkNamesFile();
  await applyCredentials();

  protocol.handle('https', async (request) => {
    const url = new URL(request.url);
    if (url.hostname === HOST && url.pathname === '/pb2/server.php' && request.method === 'POST') {
      const local = await serveLocalMap(request);
      if (local) return local;
    }
    if (url.hostname === HOST && url.pathname.startsWith(PREFIX)) {
      if (DEV_ENABLED && url.pathname.startsWith(DEV_PREFIX)) return serveDev(request, url);
      return serveLocal(url);
    }
    return net.fetch(request, { bypassCustomProtocolHandlers: true });
  });

  const win = new BrowserWindow({
    width: 1280,
    height: 720,
    autoHideMenuBar: true,
    title: 'Plazma Burst 2',
    webPreferences: { backgroundThrottling: false },
  });
  // Dev mode: print the page's console.log/warn/error to this terminal.
  win.webContents.on('console-message', (e) => {
      const src = e.sourceId ? ` (${e.sourceId.split('/').pop()}:${e.lineNumber})` : '';
      const out = e.level === 'error' ? console.error : e.level === 'warning' ? console.warn : console.log;
      out(`[page:${e.level}] ${e.message}${src}`);
    });

  win.loadURL(START_URL);
});

app.on('window-all-closed', () => app.quit());
