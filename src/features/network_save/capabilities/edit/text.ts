export const TEXT = Object.freeze({
  usage: 'netsave set|get|del <name> [value]',
  desc: 'Change, read in full, or remove one field of the local save',
  about: [
    'set writes a value, get prints one in full, del removes one. The value is typed the',
    'way the game types a downloaded save: true and false are true/false, a number is a',
    'number, anything else is text, so the value keeps its type after the next start.',
    'Everything after the name is the value, spaces included. Before the first change of',
    'a session the local save is backed up (netsave backups). The change goes online with',
    'the game\'s next upload, or now with netsave upload; some settings show only after the',
    'page is reloaded.',
  ],
  args: [
    ['set <name> <value>', 'write it, creating the field when it is new'],
    ['get <name>', 'print one value, never shortened'],
    ['del <name>', 'remove it (also unset, rm)'],
  ],
  examples: [['netsave set volume 0.5', 'the number 0.5'], ['netsave set altcur false', 'the boolean false'], ['netsave del some_field', 'remove it']],
  usageError: 'usage: netsave set <name> <value>  |  netsave get <name>  |  netsave del <name>',
  noField: (name: string) => `no field "${name}". "netsave fields ${name}" searches for it.`,
  notStorable: (text: string) => `"${text}" cannot be stored: the game drops it from the save text.`,
  value: (name: string, shown: string) => `${name} = ${shown}`,
  notSet: (name: string) => `${name} is not set`,
  removed: (name: string, was: string) => `Removed ${name} (was ${was}).`,
  changed: (name: string, shown: string, was: string | null) => `${name} = ${shown}${was === null ? '  (new)' : `  (was ${was})`}`,
  localOnly: 'The upload skips this field, so it stays in this install\'s save only.',
  kept: (id: string) => `Backed up the local save first: ${id}.`,
  backupFailed: (message: string) => `Could not back up the local save first, so nothing was changed: ${message}`,
});

