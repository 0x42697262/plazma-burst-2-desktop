export const TEXT = Object.freeze({
  countExpected: (field: string) => `${field}: expects a number or "unlimited", with < > <= >= != if you like: ${field}:>3`,
  byExpected: (words: string) => `by: expects one of ${words}, or a uid; e.g. by:timer, by:region#3, by:#timer*37`,
  byNoNumber: (word: string) => `by:${word} takes no number`,
  typeExpected: 'type: expects a number, e.g. type:99',
  findUsage: 'usage: triggers find <text>  |  uid:<text>  by:<how>  calls:<n>  maxcalls:<n>  a:<text>  b:<text>  type:<n>  (combine terms, e.g. "type:41 a:sound", "by:timer", "calls:>3")',
  moreSources: (shown: string, more: number) => `${shown}${more > 0 ? ` +${more} more` : ''}`,
  findTriggerRow: (index: string, uid: string, enabled: boolean, calls: string, actions: string, word: string, how: string) => `  #${index} ${uid} trigger   ${enabled ? 'on ' : 'off'}  ${calls} ${actions} ${word}${how ? `  by ${how}` : ''}`,
  findActionRow: (index: string, uid: string, action: string, type: string, targetA: string, targetB: string, name: string) => `  #${index} ${uid} action ${action} type ${type} A = ${targetA}   B = ${targetB}${name}`,
  triggersByUid: (count: string, byUid: boolean) => `${count}${byUid ? ' by uid' : ''}`,
  actionsIn: (actions: string, triggers: string) => `${actions} in ${triggers}`,
  findTitle: (parts: string, single: boolean, query: string) => `${parts} ${single ? 'matches' : 'match'} "${query}".`,
  findNothing: (query: string) => `No trigger or action matches "${query}"`,
  findCommand: (query: string) => `triggers find ${query}`,
});

