export const WIRE_TEXT = Object.freeze({
  unknownMessage: (word: string, names: readonly string[]) => `"${word}" is not a message. Try one of: ${names.join(', ')}`,
  ambiguousMessage: (word: string, names: readonly string[]) => `"${word}" matches more than one message: ${names.join(', ')}`,
  receiveOnly: (name: string, note: string) => `${name} is not something a client sends: ${note}`,
  unknownField: (field: string, message: string, fields: readonly string[]) => `${message} has no field "${field}". Fields: ${fields.join(', ')}`,
  unknownFlag: (flag: string, flags: readonly string[]) => `"${flag}" is not a flag. Flags: ${flags.join(', ')}`,
  tooManyValues: (message: string, count: number) => `${message} takes ${count} positional value(s); you gave more`,
  needsForce: (message: string) => `${message} re-logs your connection; add --force to send it`,
  notAChoice: (field: string, value: string, choices: readonly string[]) => `${field} must be one of: ${choices.join(', ')} (you gave "${value}")`,
  notANumber: (field: string, value: string) => `${field} must be a number (you gave "${value}")`,
  badJson: (field: string, value: string) => `${field} must be valid JSON (you gave "${value}")`,
  requiredField: (field: string, message: string) => `${message} needs ${field}; set ${field}=...`,
  noMatch: 'Not in a match: wire sends on the match or lobby connection',
  nobodyInRange: (selector: string, closest: string) => `${selector} matched nobody. Closest: ${closest}`,
  nobodyAtAll: (selector: string) => `${selector} matched nobody, and there is no one else in range`,
  tooMany: (field: string, count: number) => `${field} needs one target, but the selector matched ${count}; name just one`,
  noCrosshair: 'no crosshair position; aim with the mouse or name a target',
  resolvedTo: (field: string, who: string) => `  ${field} -> ${who}`,
  resolvedTargets: (field: string, list: string) => `  ${field} -> ${list}`,
  dryHeader: 'would send (nothing sent):',
  scaleNote: (scale: number) => `  (x${scale})`,
  replyTyped: '(reply id)',
  replyWire: '(auto)',
  dryColumns: (field: string, typed: string, wire: string, note: string) => `  ${field}  ${typed}  ${wire}${note}`,
  sent: (name: string) => `sent ${name}`,
  replyGot: (name: string, reply: string) => `${name} <- ${reply}`,
  turnedOff: (name: string, what: string) => `${name} is turned off (${what})`,
  matchMessages: 'match messages',
  lobbyMessages: 'lobby messages',
});
